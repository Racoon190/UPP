from pptx.util import Inches

prs = Presentation()
slide = prs.slides.add_slide(prs.slide_layouts[0])
slide.shapes.title.text = "Hello Deck"
slide.placeholders[1].text = "Generated by the UPP fixture script"

slide2 = prs.slides.add_slide(prs.slide_layouts[1])
slide2.shapes.title.text = "Agenda"
body = slide2.placeholders[1].text_frame
body.text = "Local parsing"
for extra in ["No network", "Bounded windows"]:
    p = body.add_paragraph()
    p.text = extra

slide3 = prs.slides.add_slide(prs.slide_layouts[5])
slide3.shapes.title.text = "Numbers"
box = slide3.shapes.add_textbox(Inches(1), Inches(2), Inches(6), Inches(2))
box.text_frame.text = "42 rows processed"
