"""Generate PDF + PPTX fixtures for doc-toolkit tests.

PDF: handcrafted minimal files (one uncompressed, one FlateDecode) so the parser
is exercised without any external PDF library.
PPTX: python-pptx (bundled runtime).
"""
import pathlib
import zlib

OUT = pathlib.Path("tests/fixtures/doc")
OUT.mkdir(parents=True, exist_ok=True)


def build_pdf(pages, compress):
    """pages: list of list of text lines."""
    objects = []

    def obj(body):
        objects.append(body)
        return len(objects)

    font_id = obj(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    page_ids = []
    content_ids = []
    for lines in pages:
        ops = ["BT", "/F1 12 Tf", "72 720 Td", "14 TL"]
        for line in lines:
            escaped = line.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")
            ops.append(f"({escaped}) Tj")
            ops.append("T*")
        ops.append("ET")
        content = ("\n".join(ops)).encode("latin-1")
        if compress:
            data = zlib.compress(content, 9)
            content_ids.append(obj(b"<< /Length %d /Filter /FlateDecode >>\nstream\n" % len(data) + data + b"\nendstream"))
        else:
            content_ids.append(obj(b"<< /Length %d >>\nstream\n" % len(content) + content + b"\nendstream"))
        page_ids.append(None)
    pages_id = len(objects) + 2 + len(pages)  # reserved below (simplify by two-pass)
    # Two-pass: write pages first with placeholder parent, then pages object.
    kids = []
    page_objs = []
    for i, _ in enumerate(pages):
        page_objs.append(obj(b"<< /Type /Page /Parent %d 0 R /MediaBox [0 0 612 792] /Contents %d 0 R /Resources << /Font << /F1 %d 0 R >> >> >>" % (0, content_ids[i], font_id)))
        kids.append(page_objs[-1])
    pages_obj = obj(b"<< /Type /Pages /Kids [%s] /Count %d >>" % (b" ".join(b"%d 0 R" % k for k in kids), len(kids)))
    # fix parents
    for pid in page_objs:
        objects[pid - 1] = objects[pid - 1].replace(b"/Parent 0 0 R", b"/Parent %d 0 R" % pages_obj)
    catalog = obj(b"<< /Type /Catalog /Pages %d 0 R >>" % pages_obj)
    info = obj(b"<< /Producer (upp-fixture) /Title (Sample PDF) >>")

    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for i, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % i + body + b"\nendobj\n"
    xref_at = len(out)
    out += b"xref\n0 %d\n" % (len(objects) + 1)
    out += b"0000000000 65535 f \n"
    for off in offsets[1:]:
        out += b"%010d 00000 n \n" % off
    out += b"trailer\n<< /Size %d /Root %d 0 R /Info %d 0 R >>\n" % (len(objects) + 1, catalog, info)
    out += b"startxref\n%d\n%%%%EOF\n" % xref_at
    return bytes(out)


plain = build_pdf(
    [
        ["Quarterly report", "Revenue grew by 12 percent", "Costs stayed flat"],
        ["Appendix", "Method notes and definitions"],
    ],
    compress=False,
)
flate = build_pdf(
    [
        ["Compressed sample", "This content stream uses FlateDecode", "Second line for the window"],
    ],
    compress=True,
)
(OUT / "sample.pdf").write_bytes(plain)
(OUT / "sample-flate.pdf").write_bytes(flate)

