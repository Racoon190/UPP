export function scan(ctx, opts) {
  const { c, o } = resolveArgs(ctx, opts)
  const kinds = Array.isArray(o.kinds) && o.kinds.length ? o.kinds : null
  const ids = Array.isArray(o.ids) ? o.ids : []
  const includeBuiltin = Boolean(o.includeBuiltin ?? c.options?.includeBuiltin)
  const account = resolveAccount(c)
  if (!isDir(c.roots.accioHome) || !account.dir) return []

  const installs = loadInstalls(c)
  let assets = []
  const want = (kind) => !kinds || kinds.includes(kind)
  const guard = (label, fn) => {
    try {
      assets.push(...fn())
    } catch (err) {
      c.log?.(`${NAME} scan ${label}: ${err.message}`)
    }
  }

  if (want('skill')) guard('skills', () => scanSkills(c, account, installs, includeBuiltin))
  if (want('plugin')) guard('plugins', () => scanPlugins(c, account, installs, includeBuiltin))
  if (want('mcp')) guard('mcp', () => scanMcp(c, account, installs))
  if (want('memory')) guard('memory', () => scanMemory(c, account))
  // kind 'tool': Accio keeps tool manifests in plugins/installed/<id>/clis/clis.json,
  // i.e. inside the plugin payload — nothing standalone to export.

  if (ids.length) {
    assets = assets.filter((a) => ids.includes(a.id) || ids.includes(`${a.kind}:${a.id}`) || ids.includes(`${a.kind}/${a.id}`))
  }
  return assets
}

function scanSkills(c, account, installs, includeBuiltin) {
  const skillsDir = path.join(account.dir, 'skills')
  const config = readJson(path.join(skillsDir, 'skills_config.json'), {}) ?? {}
  const preinstalled = readJson(path.join(skillsDir, '.preinstalled'), null)
  const preinstalledNames = new Set((preinstalled?.succeeded ?? []).map(String))
  const out = []
  for (const abs of listDirs(skillsDir)) {
    const name = path.basename(abs)
    if (name.startsWith('.')) continue
    const files = filesOf(abs)
    if (!files.length) continue
    const configKey = config[name] !== undefined ? name : config[`27_${name}`] !== undefined ? `27_${name}` : name
    const entry = config[configKey]
    const builtin = PREINSTALLED_KEY_RE.test(configKey) || preinstalledNames.has(name)
    if (builtin && !includeBuiltin) continue
    const managed = installs.byPath.get(path.resolve(abs).toLowerCase())
    out.push({
      kind: 'skill',
      host: NAME,
      id: name,
      label: name,
      version: entry?.installedVersion ?? managed?.version,
      builtin,
      strategy: 'copy-tree',
      meta: {
        skillRoot: spaceTpl(c, `skills/${name}`),
        dirName: name,
        files: files.length,
        hasScripts: hasScripts(files),
        configKey,
        enabled: entry ? entry.enabled !== false : false,
        installedVersion: entry?.installedVersion,
        managedBy: managed ? 'upp' : undefined,
        source: managed ? 'upp' : builtin ? 'registry' : 'user',
      },
      files,
    })
  }
  return out
}

function pluginManifest(dir) {
  for (const rel of PLUGIN_MANIFESTS) {
    const file = path.join(dir, rel)
    const json = readJson(file, null)
    if (json) return { file, json }
  }
  return null
}

function scanPlugins(c, account, installs, includeBuiltin) {
  const pluginsRoot = path.join(account.dir, 'plugins')
  const registry = readJson(path.join(pluginsRoot, 'plugins.json'), null)
  if (!registry || typeof registry !== 'object') return []
  const out = []
  for (const [id, raw] of Object.entries(registry)) {
    if (!raw || typeof raw !== 'object') continue
    if (id === 'version') continue
    const installedDir = path.join(pluginsRoot, 'installed', id)
    const manifest = isDir(installedDir) ? pluginManifest(installedDir) : null
    const pluginJson = manifest?.json ?? null
    const origin = String(raw.installOrigin ?? '')
    const sourceType = String(raw.sourceType ?? '')
    const local = (origin && origin !== 'remote') || /local|file/i.test(sourceType) || Boolean(raw.importedFromPath)
    const managed = installs.byName.get(`plugin:${id}`)
    const version = String(raw.version ?? pluginJson?.version ?? '')
    const label = pluginJson?.displayName ?? pluginJson?.name ?? id
    const description = pluginJson?.description

    if (local && manifest) {
      // Locally materialized plugin: fully vendorable.
      const files = filesOf(installedDir)
      out.push({
        kind: 'plugin',
        host: NAME,
        id,
        label,
        version: version || undefined,
        builtin: false,
        strategy: 'copy-tree',
        meta: {
          packageName: pluginJson?.name ?? id,
          installedVersion: version || undefined,
          source: managed ? 'upp' : 'link',
          managedBy: managed ? 'upp' : undefined,
          vendor: 'full',
          pluginId: id,
          description,
          installOrigin: origin || undefined,
          sourceType: sourceType || undefined,
          installDir: spaceTpl(c, `plugins/installed/${id}`),
          importedFromPath: raw.importedFromPath ? tplOf(c, raw.importedFromPath) : undefined,
        },
        files,
      })
      continue
    }

    // Remote / host-managed plugin: record the environment, never ship the tree.
    const files = manifest ? [{ rel: 'plugin.json', src: manifest.file }] : []
    out.push({
      kind: 'plugin',
      host: NAME,
      id,
      label,
      version: version || undefined,
      builtin: false,
      strategy: 'exec',
      meta: {
        packageName: pluginJson?.name ?? id,
        installedVersion: version || undefined,
        source: 'registry',
        vendor: 'manifest',
        hostManaged: true,
        pluginId: id,
        description,
        installOrigin: origin || undefined,
        sourceType: sourceType || undefined,
        remote: true,
        toolDiscoveryState: raw.toolDiscoveryState?.status,
        reinstall: { host: NAME, via: 'Accio plugin marketplace / gateway import', pluginId: id },
      },
      files,
    })
  }
  return out
}

function scanMcp(c, account, installs) {
  const root = path.join(account.dir, 'mcp-servers')
  const out = []
  const customFile = path.join(root, 'custom.json')
  const custom = readJson(customFile, null)
  const disabled = Array.isArray(custom?.disabledServers) ? custom.disabledServers : []
  for (const [serverName, raw] of Object.entries(custom?.servers ?? {})) {
    if (!raw || typeof raw !== 'object') continue
    const entry = c.tpl.templateValue(JSON.parse(JSON.stringify(raw)))
    const redacted = redactEnv(entry)
    const managed = installs.byName.get(`mcp:${serverName}`)
    out.push({
      kind: 'mcp',
      host: NAME,
      id: serverName,
      label: serverName,
      builtin: false,
      strategy: 'merge-json',
      meta: {
        serverName,
        configFile: spaceTpl(c, 'mcp-servers/custom.json'),
        entry,
        // Accio entries declare transport explicitly; command arrays are local stdio.
        transport: entry.transport ?? (entry.url ? 'http' : 'stdio'),
        enabled: entry.enabled !== false && !disabled.includes(serverName),
        registerMode: entry.register_mode,
        managedBy: managed ? 'upp' : undefined,
        source: managed ? 'upp' : 'user',
        redactedEnv: redacted.length ? redacted : undefined,
        fragment: { servers: { [serverName]: entry } },
        targetPath: spaceTpl(c, 'mcp-servers/custom.json'),
      },
      files: [],
      secrets: redacted.length
        ? Object.fromEntries(redacted.map((k) => [`environment.${k}`, 'value masked at export; set it again after import']))
        : undefined,
      placeholders: redacted.length
        ? Object.fromEntries(redacted.map((k) => [k, 'environment variable redacted at export']))
        : undefined,
    })
  }

  // Plugin-owned MCP files: host regenerates them when the owning plugin installs,
  // so they are exported (small, informative) but never imported.
  const pluginsMcpDir = path.join(root, 'plugins')
  let pluginFiles = []
  try {
    pluginFiles = fs
      .readdirSync(pluginsMcpDir)
      .filter((f) => f.endsWith('.json') && !isJunk(f))
      .sort()
  } catch {
    pluginFiles = []
  }
  for (const name of pluginFiles) {
    const file = path.join(pluginsMcpDir, name)
    const json = readJson(file, null)
    if (!json || typeof json !== 'object') continue
    const pluginId = String(json.pluginId ?? path.basename(name, '.json'))
    for (const [serverName, raw] of Object.entries(json.servers ?? {})) {
      if (!raw || typeof raw !== 'object') continue
      const entry = c.tpl.templateValue(JSON.parse(JSON.stringify(raw)))
      out.push({
        kind: 'mcp',
        host: NAME,
        id: `plugin:${pluginId}:${serverName}`,
        label: serverName,
        builtin: false,
        strategy: 'exec',
        meta: {
          serverName,
          configFile: spaceTpl(c, `mcp-servers/plugins/${name}`),
          entry,
          transport: entry.transport ?? (entry.url ? 'http' : 'stdio'),
          hostManaged: true,
          pluginId,
          source: 'plugin',
          reinstall: { host: NAME, via: 'install the owning Accio plugin', pluginId },
        },
        files: [],
      })
    }
  }
  return out
}

function redactEnv(entry) {
  const redacted = []
  if (entry.environment && typeof entry.environment === 'object') {
    for (const [k, v] of Object.entries(entry.environment)) {
      if (typeof v === 'string' && v && !/^\$\{/.test(v) && SECRET_ENV_RE.test(k)) {
        entry.environment[k] = `\${${k}}`
        redacted.push(k)
      }
    }
  }
  return redacted
}

function scanMemory(c, account) {
  const dir = path.join(account.dir, 'global-memory')
  let names = []
  try {
    names = fs.readdirSync(dir).filter((f) => !isJunk(f) && /\.(md|json|txt)$/i.test(f)).sort()
  } catch {
    return []
  }
  const out = []
  for (const name of names) {
    const abs = path.join(dir, name)
    let st
    try {
      st = fs.statSync(abs)
    } catch {
      continue
    }
    if (!st.isFile()) continue
    const id = slug(path.basename(name, path.extname(name))).toLowerCase()
    const ext = path.extname(name).toLowerCase() || '.md'
    out.push({
      kind: 'memory',
      host: NAME,
      id,
      label: path.basename(name, path.extname(name)),
      builtin: false,
      strategy: 'write-file',
      meta: {
        file: spaceTpl(c, `global-memory/${name}`),
        format: ext === '.json' ? 'json' : ext === '.md' ? 'markdown' : 'text',
        raw: true,
        accountScoped: true,
        payloadRel: `${id}${ext}`,
        bytes: st.size,
      },
      files: [{ rel: `${id}${ext}`, src: abs }],
    })
  }
  return out
}

