/**
 * accio.mjs — Accio Work adapter for uppenv.
 *
 * Host knowledge encoded here (verified against a real install at
 * C:\Users\Administrator\.accio, account space 1797968970):
 *
 *   ~/.accio/
 *     accounts/<account>/                          <- one directory per signed-in account ("space")
 *       skills/<name>/                             skill tree
 *       skills/skills_config.json                  {"<key>":{"enabled":true,"status":"installed","installedVersion":"..."}}
 *                                                  key is "<name>" for UPP skills, "27_<name>" for preinstalled ones.
 *                                                  THE ENTRY IS THE ENABLE AUTHORITY: no entry == installed but disabled.
 *       skills/.preinstalled                       {"succeeded":[...]} host-shipped skills
 *       mcp-servers/custom.json                    {"servers":{<name>:{type:'local',enabled,timeout,register_mode,
 *                                                  command:[...], args:[...], environment:{}, transport}}}
 *                                                  NOTE command is an ARRAY here (WorkBuddy uses a string).
 *       mcp-servers/plugins/<pluginId>.json        plugin-owned MCP servers, regenerated by the host
 *       global-memory/PROFILE.md                   user profile memory
 *       plugins/plugins.json                       {<pluginId>:{enabled,installOrigin,sourceType,toolDiscoveryState,...}}
 *       plugins/installed/<pluginId>/              plugin tree (plugin.json lookup: plugin.json ->
 *                                                  .phoenix-plugin/plugin.json -> .claude-plugin/plugin.json)
 *       .accio/runtime/gateway-cli.json            gateway endpoint + basic-auth token (NEVER exported)
 *
 * Facts that shape this adapter:
 * - Remote-installed plugins are 11–58 MB vendor trees; exporting them would be
 *   absurd and useless (they are re-downloadable), so they are recorded as
 *   manifest-only assets and skipped on import with a clear reason.
 * - Accio only fully recognizes a plugin that arrived through its gateway
 *   (POST /plugins/import-local); writing plugins.json + the tree is necessary
 *   but the adapter says so as a warning instead of pretending success.
 * - Account ids are personal data: they never enter the image. Asset paths use
 *   "${ACCIO_HOME}/accounts/{account}/..." and the account is resolved locally.
 */
