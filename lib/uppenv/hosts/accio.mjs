export const NAME = 'accio'

/** skills_config.json keys for host-preinstalled skills carry this prefix. */
const PREINSTALLED_KEY_RE = /^27_/
const JUNK_RE = [/\.upp-bak-orig$/i, /\.uppenv-(?:bak|tmp)/i, /\.recovery$/i, /^remote_skills_cache\.json$/i, /^\.preinstalled$/i]
const SECRET_ENV_RE = /(token|secret|password|passwd|api[_-]?key|apikey|access[_-]?key|credential)/i
/** Plugin manifest lookup order used by Accio itself. */
const PLUGIN_MANIFESTS = ['plugin.json', path.join('.phoenix-plugin', 'plugin.json'), path.join('.claude-plugin', 'plugin.json')]

