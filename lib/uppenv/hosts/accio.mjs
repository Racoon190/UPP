const unsupported = (reason) => ({ action: 'skip', targets: [], reason, ops: [] })

function buildPlan(asset, ctx) {
  const c = ctx && ctx.roots ? ctx : standaloneContext()
  const account = resolveAccount(c)
  if (!isDir(c.roots.accioHome)) {
    return { action: 'missing-host', targets: [], reason: `Accio home not found: ${tplOf(c, c.roots.accioHome)}`, ops: [], needs: ['accio'] }
  }
  if (!account.dir) {
    return {
      action: 'skip',
      targets: [],
      reason: 'no Accio account workspace exists; sign in to Accio once before importing',
      ops: [],
      needs: ['accio-account'],
    }
  }
  switch (asset.kind) {
    case 'skill':
      return planSkill(asset, c, account)
    case 'plugin':
      return planPlugin(asset, c, account)
    case 'mcp':
      return planMcp(asset, c, account)
    case 'memory':
      return planMemory(asset, c, account)
    case 'tool':
      // Informational snapshot of an MCP server's tool list (meta.source === 'mcp-snapshot');
      // the server itself is what gets installed, so nothing to write here.
      return {
        action: 'skip',
        targets: [],
        reason: `tool list "${asset.id}" is an informational MCP snapshot; import the mcp asset with the same name to register the server`,
        ops: [],
      }
    default:
      return unsupported(`Accio adapter cannot import kind "${asset.kind}"`)
  }
}

function planSkill(asset, c, account) {
  const meta = asset.meta ?? {}
  const dirName = String(meta.dirName ?? asset.id)
  const dest = path.join(account.dir, 'skills', dirName)
  const configFile = path.join(account.dir, 'skills', 'skills_config.json')
  const configKey = String(meta.configKey ?? dirName)
  const version = String(asset.version ?? meta.installedVersion ?? '0.0.0')
  const mutate = (base) => {
    const next = base ?? {}
    const prior = next[configKey] && typeof next[configKey] === 'object' ? next[configKey] : {}
    // The entry IS the enable authority: without it Accio treats the skill as installed-but-off.
    next[configKey] = deepMerge(prior, { enabled: meta.enabled ?? true, status: 'installed', installedVersion: version })
    return next
  }
  const treeAct = cleanTreeAction(dest, asset.dir)
  const cfg = planJson(configFile, mutate)
  const targets = [
    { path: dest, action: treeAct },
    { path: configFile, action: cfg.action, detail: `skills_config.${configKey}` },
  ]
  return { action: combineAction(targets.map((t) => t.action)), targets, ops: [
    { op: 'tree', dest, action: treeAct },
    { op: 'json', file: configFile, mutate },
  ] }
}

function planPlugin(asset, c, account) {
  const meta = asset.meta ?? {}
  if (meta.vendor === 'manifest' || !(asset.files?.length)) {
    return {
      action: 'skip',
      targets: [],
      reason: `remote Accio plugin ${meta.pluginId ?? asset.id}: only a manifest was exported (vendor trees are re-downloadable). Install it from the Accio plugin marketplace on this machine.`,
      ops: [],
      needs: ['accio-marketplace'],
    }
  }
  const pluginId = String(meta.pluginId ?? asset.id)
  const installedDir = path.join(account.dir, 'plugins', 'installed', pluginId)
  const registryFile = path.join(account.dir, 'plugins', 'plugins.json')
  const version = String(asset.version ?? meta.installedVersion ?? '0.0.0')
  const now = new Date().toISOString()
  const mutate = (base) => {
    const next = base ?? {}
    const prior = next[pluginId] && typeof next[pluginId] === 'object' ? next[pluginId] : {}
    next[pluginId] = {
      ...prior,
      enabled: prior.enabled ?? true,
      installOrigin: 'local',
      sourceType: 'local-file',
      installedAt: prior.installedAt ?? now,
      version,
      // Keep a settled discovery state on re-import; only a genuinely new plugin starts pending.
      toolDiscoveryState: prior.toolDiscoveryState ?? { status: 'pending', updatedAt: now },
    }
    return next
  }
  const treeAct = cleanTreeAction(installedDir, asset.dir)
  const targets = [
    { path: installedDir, action: treeAct },
    { path: registryFile, action: planJson(registryFile, mutate).action, detail: `plugins.${pluginId}` },
  ]
  return {
    action: combineAction(targets.map((t) => t.action)),
    targets,
    ops: [
      { op: 'tree', dest: installedDir, action: treeAct },
      { op: 'json', file: registryFile, mutate },
    ],
    warnings: [
      'Accio only fully registers a plugin imported through its gateway (POST /plugins/import-local): after import, re-add the plugin directory from the Accio UI and restart Accio if it does not appear.',
    ],
  }
}

function planMcp(asset, c, account) {
  const meta = asset.meta ?? {}
  if (meta.hostManaged) {
    return {
      action: 'skip',
      targets: [],
      reason: `MCP server owned by Accio plugin ${meta.pluginId ?? '?'}: the host regenerates mcp-servers/plugins/ when that plugin is installed`,
      ops: [],
      needs: ['accio-plugin'],
    }
  }
  const file = expandSpace(c, meta.configFile, account.id)
  if (!file) return { action: 'error', targets: [], reason: 'mcp asset has no meta.configFile', ops: [] }
  const serverName = String(meta.serverName ?? asset.id)
  const entry = resolveEnv(c, meta.entry ?? {})
  const mutate = (base) => {
    const next = base ?? {}
    next.servers = next.servers && typeof next.servers === 'object' ? next.servers : {}
    next.servers[serverName] = deepMerge(next.servers[serverName] ?? {}, entry)
    return next
  }
  const planned = planJson(file, mutate)
  return {
    action: planned.action,
    targets: [{ path: file, action: planned.action, detail: `servers.${serverName}` }],
    ops: [
      { op: 'json', file, mutate },
      { op: 'gateway', command: 'server-add', serverName, entry },
    ],
    warnings: meta.redactedEnv?.length
      ? [`environment ${meta.redactedEnv.join(', ')} was redacted at export; the ${'`'}${'${VAR}'}${'`'} placeholder stays in custom.json`]
      : undefined,
  }
}

function planMemory(asset, c, account) {
  const meta = asset.meta ?? {}
  const dest = expandSpace(c, meta.file, account.id)
  if (!dest) return { action: 'error', targets: [], reason: 'memory asset has no meta.file', ops: [] }
  const rel = String(meta.payloadRel ?? asset.files?.[0]?.rel ?? `${asset.id}.md`)
  const srcFile = sourceFile(asset, rel)
  // Compare payload bytes so an unchanged memory file plans as noop.
  const action = fileAction(dest, srcFile ? sha256File(srcFile) : undefined)
  return {
    action,
    targets: [{ path: dest, action }],
    ops: [{ op: 'file', dest, rel }],
  }
}

function resolveEnv(c, entry) {
  const out = c.tpl.expandValue(JSON.parse(JSON.stringify(entry ?? {})))
  walkStrings(out, (v) => normPathString(v))
  if (out.environment && typeof out.environment === 'object') {
    for (const [k, v] of Object.entries(out.environment)) {
      const m = typeof v === 'string' ? /^\$\{([A-Z0-9_]+)\}$/.exec(v) : null
      if (!m) continue
      out.environment[k] = c.env?.[m[1]] ?? v
    }
  }
  return out
}

export function plan(asset, ctx) {
  const c = ctx && ctx.roots ? ctx : standaloneContext()
  let built
  try {
    built = buildPlan(asset, c)
  } catch (err) {
    return { asset, action: 'error', targets: [], reason: `plan failed: ${err.message}` }
  }
  const entry = { asset, action: built.action, targets: built.targets }
  if (built.reason) entry.reason = built.reason
  if (built.needs?.length) entry.needs = built.needs
  if (built.warnings?.length) entry.warnings = built.warnings
  return entry
}

export function apply(asset, ctx, tx) {
  const c = ctx && ctx.roots ? ctx : standaloneContext()
  const dryRun = Boolean(tx?.dryRun || c.options?.dryRun)
  const onConflict = c.options?.onConflict ?? 'overwrite'
  const warnings = []
  const commands = []
  let built
  try {
    built = buildPlan(asset, c)
  } catch (err) {
    return { asset, action: 'error', targets: [], error: `plan failed: ${err.message}` }
  }
  if (built.warnings) warnings.push(...built.warnings)
  const account = resolveAccount(c)
  // Gateway registration mutates the running app; only nudge it when the config
  // file actually changed (an unchanged import must not restart servers).
  const changed = built.targets.some((t) => t.action === 'create' || t.action === 'update')

  const targets = []
  for (const op of built.ops) {
    if (op.op === 'tree') {
      if (op.action === 'noop') targets.push({ path: op.dest, action: 'noop' })
      else targets.push({ path: op.dest, action: applyCopyTree(tx, op.dest, asset.dir, { onConflict, dryRun }).action })
    } else if (op.op === 'file') {
      targets.push({ path: op.dest, action: applyFile(tx, op.dest, assetFile(asset, op.rel), { onConflict, dryRun }).action })
    } else if (op.op === 'json') {
      targets.push({ path: op.file, action: applyJsonWith(tx, op.file, op.mutate, { onConflict, dryRun }).action })
    } else if (op.op === 'gateway') {
      if (!changed) {
        commands.push({ command: `accio-mcp-cli server add (${op.serverName})`, skipped: true })
        continue
      }
      const res = registerWithGateway(c, account, op, tx, dryRun)
      if (res.command) commands.push(res.command)
      if (res.warning) warnings.push(res.warning)
    }
  }

  for (const t of targets) {
    if (t.action === 'noop') continue
    try {
      tx?.log?.({ op: t.action, path: t.path, kind: asset.kind, id: asset.id })
    } catch {
      /* journal is best-effort */
    }
  }

  if (asset.kind === 'skill' && !dryRun) warnings.push('Accio reads skills/skills_config.json on start; restart Accio if the skill stays disabled')
  const action = built.action === 'skip' || built.action === 'missing-host'
    ? built.action
    : combineAction(targets.map((t) => t.action))
  const result = { asset, action, targets, warnings: warnings.length ? warnings : undefined }
  if (commands.length) result.commands = commands
  if (built.reason) result.reason = built.reason
  return result
}

/**
 * Best-effort gateway registration (Accio's documented path for local MCP servers:
 * `accio-mcp-cli server add --json-file`). The file merge above is what makes the
 * config durable; the command only nudges the running gateway. Never fatal.
 */
function registerWithGateway(c, account, op, tx, dryRun) {
  if (dryRun) return { command: { command: 'accio-mcp-cli server add', skipped: true } }
  // Escape hatch for tests/CI on a machine where the desktop app must not be poked.
  if (c.env?.UPPENV_NO_GATEWAY) {
    return {
      command: { command: `accio-mcp-cli server add (${op.serverName})`, skipped: true },
      warning: 'gateway registration skipped (UPPENV_NO_GATEWAY); restart Accio so it reads the updated custom.json',
    }
  }
  const gwFile = [
    path.join(account.dir ?? '', '.accio', 'runtime', 'gateway-cli.json'),
    path.join(c.roots.accioHome, '.accio', 'runtime', 'gateway-cli.json'),
  ].find((p) => exists(p))
  if (!gwFile) {
    return { warning: 'Accio gateway not running: restart Accio (or reload MCP servers in its UI) so it picks up the new server' }
  }
  const gw = readJson(gwFile, null)
  const cli = findGatewayCli(c)
  if (!gw?.url || !cli) {
    return {
      warning: cli
        ? `Accio gateway metadata is missing ${gwFile}; restart Accio so the gateway registers "${op.serverName}"`
        : `accio-mcp-cli was not found (set ACCIO_MCP_CLI to its accio-mcp.mjs); restart Accio so its gateway registers "${op.serverName}"`,
    }
  }
  const payload = { ...op.entry, name: op.serverName }
  let tmp
  try {
    tmp = path.join(os.tmpdir(), `uppenv-accio-${process.pid}-${Date.now()}.json`)
    writeJson(tmp, payload)
  } catch (err) {
    return { warning: `could not stage gateway payload: ${err.message}` }
  }
  const env = {
    ACCIO_GATEWAY_TOKEN: String(gw.password ?? ''),
    ACCIO_GATEWAY_USERNAME: String(gw.username ?? ''),
    ACCIO_LOCAL_GATEWAY_URL: String(gw.url ?? ''),
  }
  const res = tx.exec('node', [`"${cli}"`, 'server', 'add', '--json-file', `"${tmp}"`], { env, timeout: 60000 })
  try {
    fs.rmSync(tmp, { force: true })
  } catch {
    /* scratch file */
  }
  const command = { command: `accio-mcp-cli server add --json-file <payload> (${op.serverName})`, status: res.status, skipped: res.skipped }
  if (res.status !== 0) {
    return {
      command,
      warning: `gateway registration returned ${res.status ?? res.error ?? 'no status'}; custom.json was still updated (Accio may report HTTP 409 if the server already exists). ${String(res.stderr || res.error || '').slice(0, 300)}`.trim(),
    }
  }
  return { command }
}

/**
 * Accio's MCP CLI ships inside the desktop app bundle, launched by the app rather
 * than PATH, so probe the usual install roots (including other drives).
 */
function findGatewayCli(c) {
  const rel = path.join('resources', 'accio-mcp-cli', 'accio-mcp.mjs')
  const candidates = [
    c.env?.ACCIO_MCP_CLI,
    path.join(c.roots.accioHome, rel),
    c.env?.LOCALAPPDATA ? path.join(c.env.LOCALAPPDATA, 'Programs', 'Accio', rel) : null,
    c.env?.LOCALAPPDATA ? path.join(c.env.LOCALAPPDATA, 'Accio', rel) : null,
    c.env?.ProgramFiles ? path.join(c.env.ProgramFiles, 'Accio', rel) : null,
    c.env?.PROGRAMFILES ? path.join(c.env.PROGRAMFILES, 'Accio', rel) : null,
    '/Applications/Accio.app/Contents/Resources/accio-mcp-cli/accio-mcp.mjs',
  ].filter(Boolean)
  const winRel = 'resources/accio-mcp-cli/accio-mcp.mjs'
  for (const letter of 'CDEFGHIJKLMNOPQRSTUVWXYZ') candidates.push(`${letter}:/Program Files/Accio/${winRel}`)
  return candidates.find((p) => exists(p)) ?? null
}

export function verify(asset, ctx) {
  const c = ctx && ctx.roots ? ctx : standaloneContext()
  if (!asset?.dir) {
    // A scan result describes the live host; only a materialized image asset
    // carries the payload that verify compares against.
    return { ok: true, skipped: true, checked: 0, reason: 'asset has no payload dir (scan result); verify applies to materialized image assets' }
  }
  const built = buildPlan(asset, c)
  // Nothing portable was applied, so there is nothing to verify.
  if (built.action === 'skip' || built.action === 'missing-host') {
    return { ok: true, skipped: true, checked: 0, reason: built.reason }
  }
  const problems = []
  for (const t of built.targets) {
    if (t.action === 'noop' || t.action === 'skip') continue
    problems.push(`${t.path}: ${t.action} (not materialized)`)
  }
  return { ok: problems.length === 0, checked: built.targets.length, problems }
}

