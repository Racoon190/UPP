export function detect(ctx) {
  const c = ctx && ctx.roots ? ctx : standaloneContext()
  const accioHome = c.roots.accioHome
  const info = { host: NAME, available: false, platform: c.roots.platform, paths: {}, counts: {}, warnings: [] }
  try {
    if (!isDir(accioHome)) {
      info.reason = `Accio home not found: ${tplOf(c, accioHome)}`
      return info
    }
    const account = resolveAccount(c)
    info.paths = { home: tplOf(c, accioHome), accounts: tplOf(c, account.accountsRoot) }
    if (!account.id) {
      info.reason = `Accio is installed but no account workspace exists under ${tplOf(c, account.accountsRoot)}; sign in to Accio once`
      return info
    }
    const space = account.dir
    const skillsDir = path.join(space, 'skills')
    const skillsConfig = readJson(path.join(skillsDir, 'skills_config.json'), null)
    const plugins = readJson(path.join(space, 'plugins', 'plugins.json'), null)
    const custom = readJson(path.join(space, 'mcp-servers', 'custom.json'), null)
    const memoryDir = path.join(space, 'global-memory')

    info.available = true
    info.version = skillsConfig?.version ?? null
    info.account = '{account}' // placeholder on purpose: account ids are personal data
    info.paths = {
      ...info.paths,
      space: spaceTpl(c, '.'),
      skills: spaceTpl(c, 'skills'),
      skillsConfig: spaceTpl(c, 'skills/skills_config.json'),
      mcp: spaceTpl(c, 'mcp-servers/custom.json'),
      plugins: spaceTpl(c, 'plugins/plugins.json'),
      memory: spaceTpl(c, 'global-memory'),
    }
    const preinstalled = readJson(path.join(skillsDir, '.preinstalled'), null)
    info.counts = {
      skills: listDirs(skillsDir).filter((d) => !path.basename(d).startsWith('.')).length,
      skillConfigEntries: Object.keys(skillsConfig ?? {}).filter((k) => k !== 'version').length,
      plugins: Object.keys(plugins ?? {}).length,
      mcpServers: Object.keys(custom?.servers ?? {}).length,
      memoryFiles: fs.existsSync(memoryDir) ? fs.readdirSync(memoryDir).filter((f) => !isJunk(f)).length : 0,
    }
    info.profile = `${info.counts.skills} skills · ${info.counts.plugins} plugins · ${info.counts.mcpServers} mcp`
    if (account.all.length > 1) info.warnings.push(`${account.all.length} Accio accounts found; using "${'{account}'}" (override with UPPENV_ACCIO_ACCOUNT=<name>)`)
    if (preinstalled?.succeeded?.length) info.counts.preinstalled = preinstalled.succeeded.length
    if (!exists(path.join(space, 'mcp-servers', 'custom.json'))) info.warnings.push('no mcp-servers/custom.json yet')
  } catch (err) {
    info.available = false
    info.reason = `Accio detect failed: ${err.message}`
  }
  return info
}

