export function scan(ctx, opts) {
  const { c, o } = resolveArgs(ctx, opts)
  const kinds = Array.isArray(o.kinds) && o.kinds.length ? o.kinds : null
  const ids = Array.isArray(o.ids) ? o.ids : []
  const includeBuiltin = Boolean(o.includeBuiltin ?? c.options?.includeBuiltin)
  const wb = c.roots.workbuddyHome
  if (!isDir(wb)) return []

  const installs = loadInstalls(c)
  let assets = []
  const want = (kind) => !kinds || kinds.includes(kind)
  const guard = (label, fn) => {
    try {
      assets.push(...fn())
    } catch (err) {
      c.log?.(`${NAME} scan ${label}: ${err.message}`)
    }
  }

  if (want('skill')) guard('skills', () => scanSkills(c, installs))
  if (want('plugin')) guard('plugins', () => scanPlugins(c, installs, includeBuiltin))
  if (want('mcp')) guard('mcp', () => scanMcp(c, installs))
  if (want('memory')) guard('memory', () => scanMemory(c))
  // kind 'tool': WorkBuddy keeps tool manifests inside plugin trees (clis/clis.json),
  // which are already part of the plugin payloads — nothing standalone to export.

  if (ids.length) {
    assets = assets.filter((a) => ids.includes(a.id) || ids.includes(`${a.kind}:${a.id}`) || ids.includes(`${a.kind}/${a.id}`))
  }
  return assets
}

function scanSkills(c, installs) {
  const dir = path.join(c.roots.workbuddyHome, 'skills')
  const out = []
  for (const abs of listDirs(dir)) {
    const name = path.basename(abs)
    if (name.startsWith('.')) continue
    const files = filesOf(abs)
    if (!files.length) continue
    const managed = installs.byPath.get(path.resolve(abs).toLowerCase())
    out.push({
      kind: 'skill',
      host: NAME,
      id: name,
      label: name,
      version: managed?.version,
      builtin: false,
      strategy: 'copy-tree',
      meta: {
        skillRoot: tplOf(c, abs),
        dirName: name,
        files: files.length,
        hasScripts: hasScripts(files),
        managedBy: managed ? 'upp' : undefined,
        source: managed ? 'upp' : undefined,
      },
      files,
    })
  }
  return out
}

function scanPlugins(c, installs, includeBuiltin) {
  const pluginsDir = path.join(c.roots.workbuddyHome, 'plugins')
  const registry = readJson(path.join(pluginsDir, 'installed_plugins.json'), {}) ?? {}
  const known = readJson(path.join(pluginsDir, 'known_marketplaces.json'), {}) ?? {}
  const out = []

  for (const [key, rawEntries] of Object.entries(registry.plugins ?? {})) {
    const at = key.lastIndexOf('@')
    const name = at === -1 ? key : key.slice(0, at)
    const marketplace = at === -1 ? UPP_MARKETPLACE : key.slice(at + 1)
    const entry = Array.isArray(rawEntries) ? rawEntries[0] : rawEntries
    if (!entry || typeof entry !== 'object') continue

    const market = known[marketplace] ?? {}
    const builtin = Boolean(market.isBuiltIn)
    if (builtin && !includeBuiltin) continue

    const pluginDir = entry.installPath
      ? path.resolve(entry.installPath)
      : path.join(String(market.installLocation ?? path.join(pluginsDir, 'marketplaces', marketplace)), 'plugins', name)
    const pluginJsonFile = path.join(pluginDir, 'plugin.json')
    const pluginJson = readJson(pluginJsonFile, null)
    const managed = installs.byName.get(key) ?? (marketplace === UPP_MARKETPLACE ? installs.byName.get(key) : undefined)
    const isUppMarketplace = marketplace === UPP_MARKETPLACE || Boolean(managed)
    const version = String(entry.version ?? pluginJson?.version ?? '')
    const description = pluginJson?.description

    if (isUppMarketplace && isDir(pluginDir)) {
      // UPP-managed marketplace plugin: fully self-contained -> vendor the tree.
      const files = filesOf(pluginDir)
      out.push({
        kind: 'plugin',
        host: NAME,
        id: key,
        label: pluginJson?.displayName ?? name,
        version: version || undefined,
        builtin,
        strategy: 'copy-tree',
        meta: {
          packageName: pluginJson?.name ?? name,
          installedVersion: version || undefined,
          source: 'upp',
          managedBy: 'upp',
          vendor: 'full',
          marketplace,
          key,
          pluginName: name,
          description,
          installPath: tplOf(c, pluginDir),
          installDir: joinTpl(tplOf(c, path.join(pluginsDir, 'marketplaces', marketplace)), `plugins/${name}`),
          scope: entry.scope ?? 'user',
        },
        files,
      })
      continue
    }

    // Host-managed marketplace plugin (builtin / cache / remote): record it as a
    // manifest-only asset — an environment image should not ship 40 vendor trees.
    const files = pluginJson && exists(pluginJsonFile) ? [{ rel: 'plugin.json', src: pluginJsonFile }] : []
    out.push({
      kind: 'plugin',
      host: NAME,
      id: key,
      label: pluginJson?.displayName ?? name,
      version: version || undefined,
      builtin,
      strategy: 'exec',
      meta: {
        packageName: pluginJson?.name ?? name,
        installedVersion: version || undefined,
        source: 'registry',
        vendor: 'manifest',
        hostManaged: true,
        marketplace,
        key,
        pluginName: name,
        description,
        reinstall: { host: NAME, marketplace, plugin: name },
      },
      files,
    })
  }
  return out
}

function scanMcp(c, installs) {
  const file = path.join(c.roots.codebuddyHome, 'mcp.json')
  const cfg = readJson(file, null)
  if (!cfg || typeof cfg !== 'object') return []
  const disabled = Array.isArray(cfg.disabledMcpServers) ? cfg.disabledMcpServers : []
  const out = []
  for (const [serverName, raw] of Object.entries(cfg.mcpServers ?? {})) {
    if (!raw || typeof raw !== 'object') continue
    const entry = c.tpl.templateValue(JSON.parse(JSON.stringify(raw)))
    const redacted = []
    if (entry.env && typeof entry.env === 'object') {
      for (const [k, v] of Object.entries(entry.env)) {
        if (typeof v === 'string' && v && !/^\$\{/.test(v) && SECRET_ENV_RE.test(k)) {
          entry.env[k] = `\${${k}}`
          redacted.push(k)
        }
      }
    }
    const managed = installs.byName.get(`mcp:${serverName}`)
    out.push({
      kind: 'mcp',
      host: NAME,
      id: serverName,
      label: serverName,
      builtin: false,
      strategy: 'merge-json',
      meta: {
        serverName,
        configFile: tplOf(c, file),
        entry,
        transport: entry.url ? 'http' : 'stdio',
        managedBy: managed ? 'upp' : undefined,
        source: managed ? 'upp' : 'user',
        enabled: !disabled.includes(serverName),
        redactedEnv: redacted.length ? redacted : undefined,
        fragment: { mcpServers: { [serverName]: entry } },
        targetPath: tplOf(c, file),
      },
      files: [],
      secrets: redacted.length
        ? Object.fromEntries(redacted.map((k) => [`env.${k}`, 'value masked at export; set it again after import']))
        : undefined,
      placeholders: redacted.length
        ? Object.fromEntries(redacted.map((k) => [k, 'environment variable redacted at export']))
        : undefined,
    })
  }
  return out
}

function scanMemory(c) {
  const dir = path.join(c.roots.workbuddyHome, 'memory')
  let names = []
  try {
    names = fs.readdirSync(dir).filter((f) => !isJunk(f) && /\.(md|json|txt)$/i.test(f)).sort()
  } catch {
    return []
  }
  const out = []
  for (const name of names) {
    const abs = path.join(dir, name)
    let st
    try {
      st = fs.statSync(abs)
    } catch {
      continue
    }
    if (!st.isFile()) continue
    const uidMatch = UID_MEMORY_RE.exec(name)
    const stem = path.basename(name, path.extname(name))
    const id = uidMatch ? 'user-memory' : slug(stem)
    const ext = path.extname(name).toLowerCase() || '.md'
    const rel = `${id}${ext}`
    // Account-scoped memory is restored as "<account>_memory.md"; the account id is
    // re-discovered on the importing machine so no uid ever enters the image.
    const file = uidMatch
      ? joinTpl(tplOf(c, dir), `{account}_memory.md`)
      : joinTpl(tplOf(c, dir), name)
    out.push({
      kind: 'memory',
      host: NAME,
      id,
      label: uidMatch ? 'user memory profile' : stem,
      builtin: false,
      strategy: 'write-file',
      meta: {
        file,
        format: ext === '.json' ? 'json' : ext === '.md' ? 'markdown' : 'text',
        raw: true,
        pii: Boolean(uidMatch),
        accountScoped: Boolean(uidMatch),
        payloadRel: rel,
        bytes: st.size,
      },
      files: [{ rel, src: abs }],
      secrets: uidMatch
        ? { accountUid: 'WorkBuddy account id embedded in the memory file name and body' }
        : undefined,
    })
  }
  return out
}

