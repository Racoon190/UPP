export const NAME = 'workbuddy'

/** Marketplace that `upp install` creates; the only one this adapter writes into. */
const UPP_MARKETPLACE = 'upp-local'
const UPP_MARKETPLACE_DESCRIPTION = 'UPP local marketplace (generated by upp CLI)'

const UID_MEMORY_RE = /^([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})_memory\.md$/i
/** Installer leftovers + host backups that must not enter an image. */
const JUNK_RE = [/\.upp-bak-orig$/i, /\.uppenv-(?:bak|tmp)/i, /\.recovery$/i]
const SECRET_ENV_RE = /(token|secret|password|passwd|api[_-]?key|apikey|access[_-]?key|credential)/i

