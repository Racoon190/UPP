/**
 * workbuddy.mjs — WorkBuddy (CodeBuddy-family desktop host) adapter for uppenv.
 *
 * Everything in this file is *host knowledge*: where WorkBuddy keeps things and
 * what shape its config files have. Mechanics (create/update/noop, merge, tree
 * replacement, rollback) live in ../core/apply.mjs and ../core/tx.mjs.
 *
 * Host layout this adapter encodes (verified against a real install):
 *
 *   ~/.workbuddy/
 *     skills/<name>/                     one directory per skill, hot-reloaded (~3 s)
 *     memory/<uuid>_memory.md            account memory; filename carries the account uid
 *     plugins/installed_plugins.json     {"version":2,"plugins":{"<name>@<marketplace>":[{scope,installPath,version,...}]}}
 *     plugins/known_marketplaces.json    {<marketplace>:{manifestName,type,source:{source,path},installLocation,...,isBuiltIn?}}
 *     plugins/marketplaces/<mp>/plugins/<name>/   real plugin trees (upp ships into "upp-local")
 *     plugins/marketplaces/<mp>/.codebuddy-plugin/marketplace.json  {name,description,plugins:[{name,version,source,description}]}
 *     storage/user-<uid>-personal/...    per-account preferences
 *   ~/.codebuddy/mcp.json                {"mcpServers":{...},"disabledMcpServers":[]}  <- the ONLY user-level MCP config
 *
 * Notes that matter for round-tripping:
 * - There is no `workbuddy skill install` / `mcp add` CLI; the files above *are*
 *   the interface, so the adapter writes them directly through the Tx.
 * - Marketplace plugins are only recognized through installed_plugins.json +
 *   known_marketplaces.json + the marketplace's .codebuddy-plugin/marketplace.json.
 * - `*.upp-bak-orig` files are UPP installer leftovers and must never ship.
 * - The memory file name embeds the account uid (personal data). It is exported
 *   under a neutral rel (`memory.md`) and restored as `<uid>_memory.md`, where the
 *   uid is re-discovered on the importing machine (see resolveAccountId).
 */
