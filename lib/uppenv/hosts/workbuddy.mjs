export function detect(ctx) {
  const c = ctx && ctx.roots ? ctx : standaloneContext()
  const wb = c.roots.workbuddyHome
  const cb = c.roots.codebuddyHome
  const info = {
    host: NAME,
    available: false,
    platform: c.roots.platform,
    paths: {},
    counts: {},
    warnings: [],
  }
  try {
    if (!isDir(wb)) {
      info.reason = `WorkBuddy home not found: ${tplOf(c, wb)}`
      return info
    }
    const skillsDir = path.join(wb, 'skills')
    const memoryDir = path.join(wb, 'memory')
    const pluginsDir = path.join(wb, 'plugins')
    const mcpFile = path.join(cb, 'mcp.json')

    const mcp = readJson(mcpFile, null)
    if (mcp === null && exists(mcpFile)) info.warnings.push(`unreadable MCP config: ${tplOf(c, mcpFile)}`)
    const registry = readJson(path.join(pluginsDir, 'installed_plugins.json'), {}) ?? {}

    info.available = true
    info.version = readJson(path.join(wb, 'app', 'package.json'), null)?.version ?? null
    info.paths = {
      home: tplOf(c, wb),
      skills: tplOf(c, skillsDir),
      memory: tplOf(c, memoryDir),
      plugins: tplOf(c, pluginsDir),
      mcpConfig: tplOf(c, mcpFile),
    }
    info.counts = {
      skills: listDirs(skillsDir).filter((d) => !path.basename(d).startsWith('.')).length,
      plugins: Object.keys(registry.plugins ?? {}).length,
      memoryFiles: fs.existsSync(memoryDir) ? fs.readdirSync(memoryDir).filter((f) => !isJunk(f)).length : 0,
      mcpServers: Object.keys(mcp?.mcpServers ?? {}).length,
    }
    info.profile = `${info.counts.skills} skills · ${info.counts.plugins} plugins · ${info.counts.mcpServers} mcp`
    if (!exists(mcpFile)) info.warnings.push('no user-level MCP config yet (~/.codebuddy/mcp.json)')
  } catch (err) {
    info.available = false
    info.reason = `WorkBuddy detect failed: ${err.message}`
  }
  return info
}

