const isJunk = (rel) => shouldIgnore(rel) || JUNK_RE.some((re) => re.test(rel))

/**
 * Resolve one payload file of an asset. Materialized image assets carry `dir` +
 * `files[].path`; raw scan assets (plan/verify on a live host) only have
 * `files[].src`, so fall back to that instead of throwing.
 */
function sourceFile(asset, rel) {
  try {
    const p = assetFile(asset, rel)
    if (p) return p
  } catch {
    /* scan assets have no payload dir */
  }
  const wanted = posix(String(rel))
  const hit = (asset.files ?? []).find((f) => f && (f.rel === wanted || posix(String(f.rel)) === wanted))
  return hit?.path ?? hit?.src ?? null
}

/**
 * Tree action that ignores host/installer backup junk. `treeAction()` in core only
 * drops default junk, so a stale `plugin.json.upp-bak-orig` next to identical content
 * would otherwise report "update" on every dry-run.
 */
function cleanTreeDigest(dir) {
  const files = []
  for (const abs of walk(dir)) {
    const rel = posix(path.relative(dir, abs))
    if (isJunk(rel)) continue
    try {
      const st = fs.statSync(abs)
      if (!st.isFile()) continue
      files.push([rel, sha256File(abs), st.size])
    } catch {
      /* unreadable files cannot be compared */
    }
  }
  files.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))
  return files.length ? sha256Json(files) : 'empty'
}

function cleanTreeAction(destDir, assetDir) {
  if (!isDir(destDir)) return !exists(destDir) ? 'create' : 'update'
  if (!isDir(assetDir)) return 'create'
  return cleanTreeDigest(destDir) === cleanTreeDigest(assetDir) ? 'noop' : 'update'
}

/** Windows separators inside expanded templates (`${UPP_STORE}/store/x` -> `\\store\\x`). */
/** Apply `fn` to every string inside a JSON-ish value (in place). */
function walkStrings(value, fn) {
  if (typeof value === 'string') return fn(value)
  if (Array.isArray(value)) {
    for (let i = 0; i < value.length; i += 1) value[i] = walkStrings(value[i], fn)
    return value
  }
  if (value && typeof value === 'object') {
    for (const k of Object.keys(value)) value[k] = walkStrings(value[k], fn)
    return value
  }
  return value
}

function normPathString(value) {
  if (typeof value !== 'string' || path.sep !== '\\') return value
  if (!/^[a-zA-Z]:[\\/]/.test(value) && !/^\\\\/.test(value)) return value
  return path.win32.normalize(value)
}

/** Build a context without the loader, for callers that invoke scan() oddly. */
function standaloneContext() {
  const roots = detectRoots()
  const tpl = createTemplates({
    HOME: roots.home,
    DSH_HOME: roots.dshHome,
    UPP_STORE: roots.uppStore,
    WORKBUDDY_HOME: roots.workbuddyHome,
    CODEBUDDY_HOME: roots.codebuddyHome,
    ACCIO_HOME: roots.accioHome,
    WORKSPACE: roots.workspace,
  })
  return { host: NAME, roots, tpl, env: process.env, options: {}, log: () => {} }
}

/**
 * Tolerate both documented shapes: scan(ctx, opts) and scan(opts) — image.mjs
 * (1.0.0) calls adapters with only the filter object, so detect that and rebuild.
 */
function resolveArgs(ctx, opts) {
  if (ctx && typeof ctx === 'object' && ctx.roots && ctx.tpl) {
    return { c: ctx, o: opts && typeof opts === 'object' ? opts : {} }
  }
  const filter = ctx && typeof ctx === 'object' ? ctx : {}
  const c = standaloneContext()
  c.options = { includeBuiltin: Boolean(filter.includeBuiltin) }
  return { c, o: { ...filter, ...(opts && typeof opts === 'object' ? opts : {}) } }
}

const tplOf = (c, abs) => c.tpl.pathToTemplate(abs) ?? abs
const joinTpl = (base, rel) => `${String(base).replace(/\/+$/, '')}/${String(rel).replace(/^\/+/, '')}`

/** Every file below `dir` as {rel, src}, minus junk. Directories are never returned. */
function filesOf(dir) {
  const out = []
  for (const abs of walk(dir)) {
    let st
    try {
      st = fs.lstatSync(abs)
      if (!st.isFile() && !st.isSymbolicLink()) continue
      if (st.isSymbolicLink() && fs.statSync(abs).isDirectory()) continue
    } catch {
      continue
    }
    const rel = posix(path.relative(dir, abs))
    if (isJunk(rel)) continue
    out.push({ rel, src: abs })
  }
  return out
}

const hasScripts = (files) => files.some((f) => /\.(py|ps1|sh|cmd|bat|js|mjs)$/i.test(f.rel))

/**
 * `~/.upp/store/<id>/<version>/.upp-install.json` records what `upp install`
 * actually wrote for each host — the authoritative "this asset is UPP-managed"
 * marker (there is no ownership metadata inside the host itself).
 */
function loadInstalls(c) {
  const byPath = new Map()
  const byName = new Map()
  const store = path.join(c.roots.uppStore, 'store')
  for (const pkg of listDirs(store)) {
    for (const ver of listDirs(pkg)) {
      const rec = readJson(path.join(ver, '.upp-install.json'), null)
      const info = { id: rec?.id ?? path.basename(pkg), version: rec?.version ?? path.basename(ver), record: rec }
      const wbHost = rec?.hosts?.workbuddy
      if (!wbHost) continue
      for (const p of wbHost.skills ?? []) byPath.set(path.resolve(p).toLowerCase(), info)
      if (wbHost.plugin?.key) byName.set(String(wbHost.plugin.key), info)
      if (wbHost.serverName) byName.set(`mcp:${wbHost.serverName}`, info)
    }
  }
  return { byPath, byName, store }
}

/** Read + mutate a JSON config file; returns the planned action without writing. */
function planJson(file, mutate) {
  const before = readJson(file, undefined)
  const next = mutate(before === undefined ? {} : JSON.parse(JSON.stringify(before)))
  const action = before === undefined ? 'create' : JSON.stringify(before) === JSON.stringify(next) ? 'noop' : 'update'
  return { file, action, next }
}

/** Deep-merge-free JSON write: hosts own their array semantics, so we mutate by hand. */
function applyJsonWith(tx, file, mutate, { onConflict = 'overwrite', dryRun = false } = {}) {
  const planned = planJson(file, mutate)
  if (planned.action === 'noop') return planned
  if (planned.action === 'update' && onConflict === 'skip') return { ...planned, action: 'skip' }
  if (!dryRun) tx.writeText(file, `${JSON.stringify(planned.next, null, 2)}\n`)
  return planned
}

const ACTION_RANK = { noop: 0, create: 1, update: 2, skip: 3, error: 4 }
function combineAction(actions) {
  let best = 'noop'
  for (const a of actions) if ((ACTION_RANK[a] ?? 0) > (ACTION_RANK[best] ?? 0)) best = a
  return best
}

