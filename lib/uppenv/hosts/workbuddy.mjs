/** @returns {{action:string,targets:Array,reason?:string,needs?:string[],ops:Array}} */
function buildPlan(asset, ctx) {
  const c = ctx && ctx.roots ? ctx : standaloneContext()
  const wb = c.roots.workbuddyHome
  const unsupported = (reason) => ({ action: 'skip', targets: [], reason, ops: [] })
  if (!isDir(wb)) {
    return { action: 'missing-host', targets: [], reason: `WorkBuddy home not found: ${tplOf(c, wb)}`, ops: [], needs: ['workbuddy'] }
  }

  switch (asset.kind) {
    case 'skill':
      return planSkill(asset, c)
    case 'plugin':
      return planPlugin(asset, c)
    case 'mcp':
      return planMcp(asset, c)
    case 'memory':
      return planMemory(asset, c)
    case 'tool':
      // Informational snapshot of an MCP server's tool list (meta.source === 'mcp-snapshot');
      // the server itself is what gets installed, so nothing to write here.
      return {
        action: 'skip',
        targets: [],
        reason: `tool list "${asset.id}" is an informational MCP snapshot; import the mcp asset with the same name to register the server`,
        ops: [],
      }
    default:
      return unsupported(`WorkBuddy adapter cannot import kind "${asset.kind}"`)
  }
}

function planSkill(asset, c) {
  const dest = path.join(c.roots.workbuddyHome, 'skills', String(asset.meta?.dirName ?? asset.id))
  const action = cleanTreeAction(dest, asset.dir)
  return {
    action: action === 'noop' ? 'noop' : action,
    targets: [{ path: dest, action, detail: 'skills dir is hot-reloaded by WorkBuddy' }],
    ops: [{ op: 'tree', dest, action }],
  }
}

function planPlugin(asset, c) {
  const meta = asset.meta ?? {}
  if (meta.vendor === 'manifest' || !(asset.files?.length)) {
    return {
      action: 'skip',
      targets: [],
      reason: `host-managed plugin ${meta.key ?? asset.id}: WorkBuddy installs it from marketplace "${meta.marketplace ?? '?'}"; nothing portable to import (re-install from the marketplace)`,
      ops: [],
      needs: ['workbuddy-marketplace'],
    }
  }
  const marketplace = String(meta.marketplace ?? UPP_MARKETPLACE)
  if (marketplace !== UPP_MARKETPLACE) {
    return {
      action: 'skip',
      targets: [],
      reason: `refusing to write into non-UPP marketplace "${marketplace}" (only "${UPP_MARKETPLACE}" is a plain directory this tool owns)`,
      ops: [],
    }
  }

  const pluginsDir = path.join(c.roots.workbuddyHome, 'plugins')
  const marketplaceDir = path.join(pluginsDir, 'marketplaces', marketplace)
  const pluginName = String(meta.pluginName ?? meta.packageName ?? asset.id).replace(/@.*$/, '')
  const key = String(meta.key ?? `${pluginName}@${marketplace}`)
  const destDir = path.join(marketplaceDir, 'plugins', pluginName)
  const version = String(asset.version ?? meta.installedVersion ?? '0.0.0')
  const now = new Date().toISOString()
  const description = meta.description

  const marketplaceFile = path.join(marketplaceDir, '.codebuddy-plugin', 'marketplace.json')
  const registryFile = path.join(pluginsDir, 'installed_plugins.json')
  const knownFile = path.join(pluginsDir, 'known_marketplaces.json')

  const treeAct = cleanTreeAction(destDir, asset.dir)
  const ops = [
    { op: 'tree', dest: destDir, action: treeAct },
    {
      op: 'json',
      file: marketplaceFile,
      mutate: (base) => {
        const next = base ?? {}
        next.name = next.name ?? marketplace
        next.description = next.description ?? UPP_MARKETPLACE_DESCRIPTION
        const list = Array.isArray(next.plugins) ? next.plugins : []
        const item = { name: pluginName, version, source: `./plugins/${pluginName}`, description }
        const at = list.findIndex((p) => p && p.name === pluginName)
        if (at === -1) list.push(item)
        else list[at] = deepMerge(list[at], item)
        next.plugins = list
        return next
      },
    },
    {
      op: 'json',
      file: registryFile,
      mutate: (base) => {
        const next = base ?? {}
        next.version = next.version ?? 2
        next.plugins = next.plugins && typeof next.plugins === 'object' ? next.plugins : {}
        const prior = Array.isArray(next.plugins[key]) ? next.plugins[key] : []
        const priorEntry = prior.find((p) => p && p.scope === (meta.scope ?? 'user'))
        const entry = {
          scope: meta.scope ?? 'user',
          installPath: destDir,
          version,
          installedAt: priorEntry?.installedAt ?? now,
          lastUpdated: priorEntry?.lastUpdated ?? now,
        }
        next.plugins[key] = [...prior.filter((p) => p && p.scope !== entry.scope), entry]
        return next
      },
    },
    {
      op: 'json',
      file: knownFile,
      mutate: (base) => {
        const next = base ?? {}
        if (next[marketplace]) return next // existing marketplace metadata wins
        next[marketplace] = {
          manifestName: marketplace,
          type: 'directory',
          source: { source: 'directory', path: marketplaceDir },
          installLocation: marketplaceDir,
          description: UPP_MARKETPLACE_DESCRIPTION,
          lastUpdated: now,
          autoUpdate: false,
          isBuiltIn: false,
        }
        return next
      },
    },
  ]

  const targets = [
    { path: destDir, action: treeAct },
    { path: marketplaceFile, action: planJson(marketplaceFile, ops[1].mutate).action },
    { path: registryFile, action: planJson(registryFile, ops[2].mutate).action },
    { path: knownFile, action: planJson(knownFile, ops[3].mutate).action },
  ]
  return { action: combineAction(targets.map((t) => t.action)), targets, ops }
}

function planMcp(asset, c) {
  const meta = asset.meta ?? {}
  const file = expandPath(c, meta.configFile)
  if (!file) return { action: 'error', targets: [], reason: 'mcp asset has no meta.configFile', ops: [] }
  const serverName = String(meta.serverName ?? asset.id)
  const entry = resolveEnv(c, meta.entry ?? {})
  const enabled = meta.enabled !== false
  const mutate = (base) => {
    const next = base ?? {}
    next.mcpServers = next.mcpServers && typeof next.mcpServers === 'object' ? next.mcpServers : {}
    next.mcpServers[serverName] = deepMerge(next.mcpServers[serverName] ?? {}, entry)
    const disabled = Array.isArray(next.disabledMcpServers) ? next.disabledMcpServers.filter((n) => n !== serverName) : []
    if (!enabled) disabled.push(serverName)
    if (disabled.length || Array.isArray(next.disabledMcpServers)) next.disabledMcpServers = disabled
    return next
  }
  const planned = planJson(file, mutate)
  return {
    action: planned.action === 'noop' ? 'noop' : planned.action,
    targets: [{ path: file, action: planned.action, detail: `mcpServers.${serverName}` }],
    ops: [{ op: 'json', file, mutate }],
    warnings: meta.redactedEnv?.length
      ? [`env ${meta.redactedEnv.join(', ')} was redacted at export; the placeholder ${'`'}${'${VAR}'}${'`'} is kept in mcp.json`]
      : undefined,
  }
}

/** WB memory filenames are "<account-uid>_memory.md"; rediscover the uid locally. */
function resolveAccountId(c) {
  const wb = c.roots.workbuddyHome
  const memoryDir = path.join(wb, 'memory')
  try {
    for (const f of fs.readdirSync(memoryDir)) {
      const m = UID_MEMORY_RE.exec(f)
      if (m) return m[1]
    }
  } catch {
    /* no memory dir yet */
  }
  try {
    for (const d of fs.readdirSync(path.join(wb, 'storage'))) {
      const m = /^user-(.+)-personal$/.exec(d)
      if (m) return m[1]
    }
  } catch {
    /* no storage dir yet */
  }
  const snap = readJson(path.join(wb, 'storage', 'skeleton', 'account-snapshot.json'), null)
  if (snap) {
    const stack = [snap]
    while (stack.length) {
      const cur = stack.pop()
      if (!cur || typeof cur !== 'object') continue
      for (const [k, v] of Object.entries(cur)) {
        if (typeof v === 'string' && /^(uid|userId|accountId|uuid)$/i.test(k) && /^[0-9a-z-]{8,}$/i.test(v)) return v
        if (v && typeof v === 'object') stack.push(v)
      }
    }
  }
  return null
}

function planMemory(asset, c) {
  const meta = asset.meta ?? {}
  const rel = String(meta.payloadRel ?? asset.files?.[0]?.rel ?? asset.id)
  let dest = expandPath(c, meta.file)
  if (!dest) return { action: 'error', targets: [], reason: 'memory asset has no meta.file', ops: [] }
  if (meta.accountScoped) {
    const account = resolveAccountId(c)
    if (!account) {
      return {
        action: 'skip',
        targets: [],
        reason: 'cannot determine the WorkBuddy account id needed for "<account>_memory.md" (sign in to WorkBuddy once, then re-run)',
        ops: [],
        needs: ['workbuddy-account'],
      }
    }
    dest = dest.replace('{account}', account)
  }
  const srcFile = sourceFile(asset, rel)
  // Compare payload bytes so an unchanged memory file plans as noop.
  const plannedAction = fileAction(dest, srcFile ? sha256File(srcFile) : undefined)
  return {
    action: plannedAction,
    targets: [{ path: dest, action: plannedAction }],
    ops: [{ op: 'file', dest, rel }],
  }
}

/** Expand `${TOKEN}` placeholders; unknown tokens stay literal so imports stay portable. */
function expandPath(c, value) {
  if (!value || typeof value !== 'string') return null
  return normPathString(String(c.tpl.expandValue(value)))
}

/** Restore redacted env placeholders from the importing machine's environment. */
function resolveEnv(c, entry) {
  const out = c.tpl.expandValue(JSON.parse(JSON.stringify(entry ?? {})))
  walkStrings(out, (v) => normPathString(v))
  if (out.env && typeof out.env === 'object') {
    for (const [k, v] of Object.entries(out.env)) {
      const m = typeof v === 'string' ? /^\$\{([A-Z0-9_]+)\}$/.exec(v) : null
      if (!m) continue
      out.env[k] = c.env?.[m[1]] ?? v
    }
  }
  return out
}

export function plan(asset, ctx) {
  const c = ctx && ctx.roots ? ctx : standaloneContext()
  let built
  try {
    built = buildPlan(asset, c)
  } catch (err) {
    return { asset, action: 'error', targets: [], reason: `plan failed: ${err.message}` }
  }
  const entry = { asset, action: built.action, targets: built.targets }
  if (built.reason) entry.reason = built.reason
  if (built.needs?.length) entry.needs = built.needs
  if (built.warnings?.length) entry.warnings = built.warnings
  return entry
}

export function apply(asset, ctx, tx) {
  const c = ctx && ctx.roots ? ctx : standaloneContext()
  const dryRun = Boolean(tx?.dryRun || c.options?.dryRun)
  const onConflict = c.options?.onConflict ?? 'overwrite'
  const warnings = []
  let built
  try {
    built = buildPlan(asset, c)
  } catch (err) {
    return { asset, action: 'error', targets: [], error: `plan failed: ${err.message}` }
  }
  if (built.warnings) warnings.push(...built.warnings)

  const targets = []
  for (const op of built.ops) {
    if (op.op === 'tree') {
      // Skip replacement when only host backup junk differs, so import never deletes
      // files it did not create just to reach an identical tree.
      if (op.action === 'noop') {
        targets.push({ path: op.dest, action: 'noop' })
      } else {
        const res = applyCopyTree(tx, op.dest, asset.dir, { onConflict, dryRun })
        targets.push({ path: op.dest, action: res.action })
      }
    } else if (op.op === 'file') {
      const res = applyFile(tx, op.dest, assetFile(asset, op.rel), { onConflict, dryRun })
      targets.push({ path: op.dest, action: res.action })
    } else if (op.op === 'json') {
      const res = applyJsonWith(tx, op.file, op.mutate, { onConflict, dryRun })
      targets.push({ path: op.file, action: res.action })
    }
  }

  if (asset.kind === 'skill' && !dryRun) {
    warnings.push('WorkBuddy watches ~/.workbuddy/skills and reloads it within a few seconds')
  }
  if (asset.kind === 'plugin' && !dryRun) {
    warnings.push('restart WorkBuddy (or toggle the plugin in the UI) so installed_plugins.json is re-read')
  }

  for (const t of targets) {
    if (t.action === 'noop') continue
    try {
      tx?.log?.({ op: t.action, path: t.path, kind: asset.kind, id: asset.id })
    } catch {
      /* journal is best-effort */
    }
  }

  const actions = targets.map((t) => t.action)
  const action = built.action === 'skip' || built.action === 'missing-host'
    ? built.action
    : combineAction(actions.length ? actions : [built.action])
  const result = { asset, action, targets, warnings: warnings.length ? warnings : undefined }
  if (built.reason) result.reason = built.reason
  return result
}

export function verify(asset, ctx) {
  const c = ctx && ctx.roots ? ctx : standaloneContext()
  if (!asset?.dir) {
    // A scan result describes the live host; only a materialized image asset
    // carries the payload that verify compares against.
    return { ok: true, skipped: true, checked: 0, reason: 'asset has no payload dir (scan result); verify applies to materialized image assets' }
  }
  const built = buildPlan(asset, c)
  // Nothing portable was applied, so there is nothing to verify: report it honestly
  // instead of a fake failure.
  if (built.action === 'skip' || built.action === 'missing-host') {
    return { ok: true, skipped: true, checked: 0, reason: built.reason }
  }
  const problems = []
  for (const t of built.targets) {
    if (t.action === 'noop' || t.action === 'skip') continue
    problems.push(`${t.path}: ${t.action} (not materialized)`)
  }
  return { ok: problems.length === 0, checked: built.targets.length, problems }
}

